package com.blendique;

public class customization {

    private String roastCode;
    private String sizeCode;
    private String temperatureCode;
    private String iceCode;
    private String milkCode;
    private String shotsCode;
    private String addonCode;

    private double totalPrice;

    public String getRoastCode() {
        return roastCode;
    }

    public void setRoastCode(String roastCode) {
        this.roastCode = roastCode;
    }

    public String getSizeCode() {
        return sizeCode;
    }

    public void setSizeCode(String sizeCode) {
        this.sizeCode = sizeCode;
    }

    public String getTemperatureCode() {
        return temperatureCode;
    }

    public void setTemperatureCode(String temperatureCode) {
        this.temperatureCode = temperatureCode;
    }

    public String getIceCode() {
        return iceCode;
    }

    public void setIceCode(String iceCode) {
        this.iceCode = iceCode;
    }

    public String getMilkCode() {
        return milkCode;
    }

    public void setMilkCode(String milkCode) {
        this.milkCode = milkCode;
    }

    public String getShotsCode() {
        return shotsCode;
    }

    public void setShotsCode(String shotsCode) {
        this.shotsCode = shotsCode;
    }

    public String getAddonCode() {
        return addonCode;
    }

    public void setAddonCode(String addonCode) {
        this.addonCode = addonCode;
    }

    public double getTotalPrice() {
        return totalPrice;
    }

    public void setTotalPrice(double totalPrice) {
        this.totalPrice = totalPrice;
    }
}